bool fallback_font_get_character(e_utf32 utf_character, s_font_character const** out_character, void const** out_pixel_data)
{
    mangled_ppc("?fallback_font_get_character@@YA_NW4e_utf32@@PAPBUs_font_character@@PAPBX@Z");

    bool success = false;

    assert_tag_debug_untracked_jul_11_2011(677, g_fallback_font_header);
    assert_tag_debug_untracked_jul_11_2011(678, g_fallback_font_header->location_table_offset+g_fallback_font_header->location_table_count*sizeof(dword)<=sizeof(k_fallback_font_data));

    if (utf_character >= 0 && utf_character < g_fallback_font_header->location_table_count)
    {
        unsigned long const* location_table = reinterpret_cast<unsigned long const*>(k_fallback_font_data + g_fallback_font_header->location_table_offset);
        unsigned long location = location_table[utf_character];

        if (location != NONE)
        {
            long page_count = (location & 0xFFE00000) >> k_font_location_page_index_bits;
            long page_index = location & 0x1FFFFF;
            long character_offset = g_fallback_font_header->character_data_offset + k_font_character_page_size * page_index;
            s_font_character const* character = reinterpret_cast<s_font_character const*>(k_fallback_font_data + character_offset);

            assert_tag_debug_untracked_jul_11_2011(693, page_count>0 && page_count<=k_font_character_maximum_pages);
            assert_tag_debug_untracked_jul_11_2011(694, page_index>=0 && page_index+page_count<=g_fallback_font_header->character_data_size_bytes/k_font_character_page_size);
            assert_tag_debug_untracked_jul_11_2011(696, character_offset>=0 && character_offset+sizeof(s_font_character)<=sizeof(k_fallback_font_data));
            assert_tag_debug_untracked_jul_11_2011(697, font_character_validate(character));
            assert_tag_debug_untracked_jul_11_2011(698, character->packed_size>0 && character->packed_size+sizeof(s_font_character)<=page_count*k_font_character_page_size);

            *out_character = character;
            *out_pixel_data = offset_pointer(character, sizeof(s_font_character));

            success = true;
        }
    }

    return success;
};

