void c_authored_camera::update(e_output_user_index output_user_index, float dt, s_observer_command * result)
{
    mangled_ppc("?update@c_authored_camera@@UAAXW4e_output_user_index@@MPAUs_observer_command@@@Z");

    unsigned long camera_mask = saved_film_manager_get_simulation_camera_update_mask();
    bool updated_first_person = false;
    bool zoomed = false;

    if (TEST_BIT(camera_mask, 0))
    {
        s_simulation_camera_update simulation_camera_update;
        if (saved_film_manager_get_simulation_camera_updates(0, &simulation_camera_update))
        {
            long target_unit_index = NONE;
            if (simulation_camera_update.camera_type != _simulation_update_camera_none &&
                simulation_camera_update.target_absolute_player_index != NONE)
            {
                player_datum * player = static_cast<player_datum *>(datum_try_and_get_absolute(player_data, simulation_camera_update.target_absolute_player_index));
                if (player && !player->flags.test(_player_left_game_bit))
                {
                    long player_index = player_index_from_absolute_player_index(simulation_camera_update.target_absolute_player_index);
                    assert_tag_debug_untracked_jul_11_2011(123, player_index != NONE);

                    player_mapping_attach_output_user(output_user_index, player_index);
                    target_unit_index = player->unit_index;
                }
            }

            if (simulation_camera_update.camera_type == _simulation_update_camera_first_person)
            {
                m_first_person_camera.set_target(target_unit_index);
                m_first_person_camera.update(output_user_index, dt, result);
                updated_first_person = true;
            }
            else if (simulation_camera_update.camera_type == _simulation_update_camera_third_person_or_flying)
            {
                c_camera::set_target(target_unit_index);
                m_position = simulation_camera_update.position;
                m_forward = simulation_camera_update.forward;
                result->focus_position = m_position;
                result->forward = m_forward;
                generate_up_vector3d(&result->forward, &result->up);
                result->horizontal_field_of_view = simulation_camera_update.zoomed ?
                    g_camera_globals.flying_camera_zoomed_field_of_view * k_degrees_to_radians :
                    observer_suggested_field_of_view();
                if (m_last_zoomed != simulation_camera_update.zoomed)
                {
                    result->parameter_timers[4] = g_camera_globals.flying_camera_zoom_transition_time;
                    result->parameter_flags[4] = true;
                }
                result->timer = target_unit_index == NONE ? k_authored_camera_observer_result_interpolation_time_seconds : 0.0f;
                result->flags = FLAG(_observer_command_valid_bit) | FLAG(_observer_command_can_modify_fov_bit);
                zoomed = simulation_camera_update.zoomed;
            }
        }
    }

    m_last_update_first_person = updated_first_person;
    m_last_zoomed = zoomed;
};

